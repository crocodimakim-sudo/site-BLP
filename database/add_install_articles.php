<p><strong>Шаг 1. Проверка подсистемы.</strong> Подсистема имеет пазы для кляммеров, пазы чистые без мусора, ширина паза соответствует ширине кляммера, глубина достаточна для фиксации панели.</p>

<p><strong>Шаг 2. Укладка первой панели.</strong> Установить временный профиль поддержки внизу, уложить первую панель, вставить кляммеры в пазы подсистемы — они фиксируют панель без видимых отверстий. Выровнять по уровню.</p>

<p><strong>Шаг 3. Последующие ряды.</strong> Поднять временный профиль, уложить следующую панель, вставить кляммеры в пазы, контролировать зазор 8 мм между панелями (проставки), выровнять по уровню, зафиксировать кляммерами. <strong>Монтаж снизу вверх.</strong></p>

<p><strong>Шаг 4. После монтажа.</strong> Удалить временные профили поддержки, проверить надёжность фиксации всех кляммеров, убедиться, что нет видимых точек крепления на лицевой стороне.</p>

<h3>Клеевое крепление — пошагово</h3>

<p><strong>Шаг 1. Подготовка клея и инструмента.</strong> Использовать специальный фасадный клей для фиброцемента. Подготовить шпатель с зубцами, уровень, прокладки из резины для защиты поверхности.</p>

<p><strong>Шаг 2. Нанесение клея.</strong> Нанести клей на панель тонким слоем (или на подсистему — зависит от инструкции клея), распределить равномерно зубчатым шпателем.</p>

<p><strong>Шаг 3. Укладка и выравнивание.</strong> Уложить панель на клей, слегка прижать, контролировать вертикаль уровнем. Не давить чрезмерно — выдавит клей. Оставить зазоры между панелями 8 мм.</p>

<p><strong>Шаг 4. Высыхание.</strong> Следовать инструкции производителя клея, обычно 24–48 часов перед герметизацией. Защитить от дождя.</p>

<h2>День 4: завершение работ</h2>

<h3>Удаление проставок и контроль качества</h3>
<p>Аккуратно удаляем все проставки, чтобы не повредить кромки — мягким инструментом. Проверяем, что все панели надёжно зафиксированы, зазоры ровные и единообразные, на поверхности нет сколов и трещин.</p>

<h3>Герметизация швов</h3>
<p><strong>Вертикальные зазоры</strong> уже закрыты уплотнителем на направляющих подсистемы — дополнительная герметизация не требуется.</p>
<p><strong>Горизонтальные зазоры</strong>: вариант 1 — оставить открытыми для вентиляции; вариант 2 — нанести нейтральный силиконовый герметик после очистки зазора от пыли, разгладить инструментом, оставить высыхать; вариант 3 — установить декоративные планки над панелями, подрезать верхний край для предотвращения смещения.</p>

<h3>Обработка периметра и примыканий</h3>
<ol>
<li>Герметизировать примыкания к оконным проёмам — только нейтральным герметиком</li>
<li>Обработать углы фасада защитными уголками, если предусмотрены проектом</li>
