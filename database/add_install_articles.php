<h2>Часть 4. Подсистема для монтажа</h2>

<h3>Основные требования</h3>
<p><strong>Запрещено:</strong> крепление панелей непосредственно к основанию (стене).</p>
<p><strong>Обязательно:</strong> монтаж только на предварительно смонтированную подсистему.</p>

<h3>Типы подсистем</h3>
<p><strong>Вертикальная подсистема (рекомендуется).</strong> Конструкция: вертикальные стойки профиля, горизонтальные направляющие, минимум 2 горизонтальных профиля на панель при стандартных размерах. Преимущества: максимальная долговечность, правильная циркуляция воздуха, эффективная вентиляция через зазор.</p>
<p><strong>Горизонтальная подсистема.</strong> Требование: только перфорированный профиль для свободного движения воздуха. Имеет повышенный риск дефектов из-за нарушения циркуляции воздуха, поэтому применяется ограниченно.</p>

<h3>Размеры вентиляционного зазора</h3>
<p>Минимальный вентилируемый зазор — <strong>25 мм</strong>. Этот зазор обеспечивает циркуляцию воздуха, испарение влаги и предотвращение деформации панелей.</p>

<h3>Расчёт подсистемы</h3>
<p>Расчёт несущей конструкции должен учитывать: толщину утеплителя, величину вентиляционного зазора, расчётную ветровую нагрузку, собственный вес панелей. Расположение панелей влияет на количество промежуточных профилей и расположение стыковочных профилей.</p>

