<h2>Часть 6. Технология монтажа</h2>

<h3>Последовательность работ</h3>

<p><strong>Шаг 1. Подготовка до монтажа.</strong> Проверить соответствие подсистемы проекту, акклиматизировать панели к местным условиям, разложить вертикально «на ребро», использовать мягкие прокладки между листами.</p>

<p><strong>Шаг 2. Подготовка панелей перед монтажом.</strong> Визуальный осмотр на сколы и трещины, резка при необходимости, сверление отверстий, обработка торцов наждачной бумагой P80, гидрофобизирующая обработка обрезанных кромок при наличии заводского покрытия.</p>

<h3>Шаг 3. Монтаж — направление зависит от системы</h3>

<p><strong>Видимое крепление заклёпками.</strong> Разметить положение нижнего торца панели, лазерным уровнем выставить горизонталь по периметру, установить временный горизонтальный профиль поддержки. Монтаж — <strong>сверху вниз</strong>, слева направо, каждый ряд полностью перед следующим.</p>

<p><strong>Скрытое крепление кляммерами.</strong> Разметить положение нижнего торца, выставить лазерный уровень, установить временный профиль. Монтаж — <strong>снизу вверх</strong>, слева направо.</p>

<p><strong>Клеевое крепление.</strong> Подготовить основание (очистить, выровнять), разметить положение панелей, нанести клей по инструкции производителя, прижать панель сверху вниз.</p>

<h3>Контроль геометрии</h3>
<p>Лазерный уровень используется для каждого ряда. Проверяется прямолинейность вертикальных швов. Ширина зазоров контролируется проставками, которые удаляются аккуратно после установки панели.</p>

<h3>Крепление панели в точке</h3>
<p>Количество точек крепления зависит от размера панели, проектных требований ветровой нагрузки и типа крепления (видимое/скрытое).</p>
<p><strong>Типовая схема для стандартной панели 1200×2440 мм:</strong></p>
<ul>
<li>Видимое (заклёпки): минимум 4 точки по углам, рекомендуется 6–8 точек в зависимости от ветровой нагрузки</li>
<li>Скрытое (кляммеры): по рекомендациям производителя подсистемы, обычно 2–3 точки на расстояние 400–600 мм</li>
</ul>

<h3>Правила работы с панелями</h3>
<p><strong>Запрещено:</strong> сбрасывание панелей с высоты, трение панелей друг о друга, нанесение ударов по панелям, хождение по поверхности панелей.</p>
<p><strong>Правило:</strong> обращаться с панелями аккуратно, минимизируя риск механических повреждений. При переноске — вертикальное положение «на ребро», два работника на стандартную панель, мягкие прокладки при установке на торец.</p>

