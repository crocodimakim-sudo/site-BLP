                <p>Грамотное оформление узловых примыканий — залог долговечности фасада. Именно в углах, у оконных проёмов и в зоне цоколя чаще всего накапливается влага и возникают дефекты при некачественном монтаже.</p>

                <p><strong>Внешние углы</strong> оформляются алюминиевым угловым профилем, который крепится к Z-образному профилю подсистемы. Альтернатива — стыковка панелей под 45° с обязательной фаской 3–5 мм и заполнением нейтральным силиконовым герметиком. Детальные узловые решения для BLP Board — в альбоме технических решений АТР-BLP-001 (запрос через <a href="/contacts">форму обратной связи</a>).</p>

                <p><strong>Оконные и дверные проёмы:</strong> панели не должны плотно примыкать к коробке — зазор не менее <strong>10 мм</strong>. Откосы закрываются металлическими или фиброцементными элементами. Под каждым оконным проёмом устанавливается подоконный отлив с уклоном не менее 5° наружу. По периметру проёмов монтируются противопожарные отсечки из оцинкованной стали.</p>

                <ul class="install-step-list">
                    <li>Цоколь: нижний край панелей — <strong>50–100 мм от отмостки</strong>; в нижнем профиле — дренажные отверстия Ø10–12 мм с шагом 1–2 м.</li>
                    <li>Парапет: карнизная планка закрывает верхний край панелей и вентзазор; зазор под карнизом — 10–15 мм.</li>
                    <li>Деформационные швы в фасаде — через каждые 12–18 м по горизонтали, ширина 15–25 мм.</li>
                    <li>Внутренние углы: прямой стык с зазором 4–8 мм, заполненным уплотнительным жгутом и нейтральным герметиком.</li>
                </ul>

                <div class="install-step-tip">
                    <strong>Для архитекторов и проектировщиков:</strong> Полный <a href="/architect">альбом узлов НВФ</a> с типовыми решениями по углам, откосам, парапету и цоколю доступен по запросу.
                </div>
            </div>
        </div>

        <!-- ШАГ 6 -->
        <div class="install-step" id="step-6">
            <div class="install-step-num"><span>6</span></div>
            <div class="install-step-content">
                <h2 class="install-step-title">Типовые ошибки монтажа — что НЕ делать</h2>

                <p>Большинство проблем с фиброцементными фасадами возникают не из-за дефектов материала, а из-за нарушений технологии монтажа. Ниже — наиболее критичные ошибки, которые встречаются на практике.</p>

                <div class="install-mistakes-grid">
                    <div class="install-mistake-card">
                        <div class="install-mistake-icon">✗</div>
                        <h3>Не обработаны торцы после резки</h3>
                        <p>Незащищённый торец впитывает влагу → при замерзании расширяется → кромка разрушается. Обрабатывайте торец гидрофобизатором сразу после реза.</p>
                    </div>
                    <div class="install-mistake-card">
                        <div class="install-mistake-icon">✗</div>
                        <h3>Перетяжка крепёжных элементов</h3>
                        <p>Шуруп или заклёпка «насухо» создаёт точечное напряжение. При температурных деформациях панель трескается у отверстия. Оставляйте 1 мм под шляпкой.</p>
                    </div>
                    <div class="install-mistake-card">
                        <div class="install-mistake-icon">✗</div>
                        <h3>Герметик в швах без уплотнительного жгута</h3>
                        <p>Без жгута (Вилатерм Ø8–10 мм) герметик проваливается в вентзазор и блокирует вентиляцию. Результат — плесень и гниение подсистемы.</p>
                    </div>
                    <div class="install-mistake-card">
                        <div class="install-mistake-icon">✗</div>
                        <h3>Вентзазор менее 40 мм</h3>
                        <p>Недостаточный зазор нарушает конвекцию — влага не уходит, накапливается на задней стороне панелей и в утеплителе. Минимум по норме — 40 мм.</p>
                    </div>
                    <div class="install-mistake-card">
                        <div class="install-mistake-icon">✗</div>
                        <h3>Кислотный силиконовый герметик</h3>
                        <p>Кислотный (уксусный) силикон реагирует с цементом в составе панели, выделяет уксусную кислоту и разрушает панель. Используйте только <strong>нейтральный</strong> силикон.</p>
                    </div>
                    <div class="install-mistake-card">
                        <div class="install-mistake-icon">✗</div>
                        <h3>Монтаж без термовставок на кронштейнах</h3>
                        <p>Металлический кронштейн без паронитовой прокладки — прямой мостик холода. Зимой на нём образуется конденсат, который промачивает утеплитель изнутри.</p>
                    </div>
                    <div class="install-mistake-card">
                        <div class="install-mistake-icon">✗</div>
                        <h3>Резка болгаркой с алмазным диском</h3>
                        <p>Болгарка перегревает панель, вызывает микротрещины и создаёт опасную мелкодисперсную пыль. Для резки — только погружная пила с твёрдосплавным диском.</p>
                    </div>
                    <div class="install-mistake-card">
                        <div class="install-mistake-icon">✗</div>
                        <h3>Стыки панелей «в воздухе»</h3>
                        <p>Стык между панелями должен приходиться на несущий профиль подсистемы. Стык «в воздухе» со временем прогибается и трескается по торцу.</p>
                    </div>
                </div>

                <p style="margin-top: 1.5rem;">Полный разбор 20 типовых ошибок с последствиями и мерами предотвращения — в технической документации. Запросите её через <a href="/contacts">форму обратной связи</a>.</p>
            </div>
        </div>

