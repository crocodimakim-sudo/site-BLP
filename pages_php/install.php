        <div class="install-step" id="step-7">
            <div class="install-step-num"><span>7</span></div>
            <div class="install-step-content">
                <h2 class="install-step-title">Чек-лист приёмки фасада</h2>

                <p>Финальная приёмка — обязательный этап, который фиксирует качество выполненных работ и является основанием для подписания актов КС-2 / КС-3. Проверяйте каждый пункт до подписания.</p>

                <ul class="install-checklist">
                    <li>
                        <strong>Плоскостность фасада</strong> — проверить правилом 3 м со щупом. Допуск: <strong>±5 мм на 3 м</strong>.
                    </li>
                    <li>
                        <strong>Отклонение от вертикали</strong> — проверить отвесом или лазерным уровнем. Допуск: <strong>±2 мм на 3 м</strong>.
                    </li>
                    <li>
                        <strong>Ширина швов между панелями</strong> — штангенциркулем. Допуск: <strong>±1 мм</strong> от проектного значения.
                    </li>
                    <li>
                        <strong>Герметичность швов</strong> — визуально по всей длине. Пустоты, пузыри, отслоения — не допускаются.
                    </li>
                    <li>
                        <strong>Дренаж вентзазора</strong> — влить 1 л воды в верхнюю часть вентзазора. Вода должна вытечь через дренажные отверстия за <strong>2–3 минуты</strong>.
                    </li>
                    <li>
                        <strong>Вентиляция</strong> — убедиться, что приточный профиль снизу и выходная щель в карнизе не заблокированы.
                    </li>
                    <li>
                        <strong>Состояние всех панелей</strong> — отсутствие сколов, трещин, царапин на лицевой поверхности, оставленных в процессе монтажа.
                    </li>
                    <li>
                        <strong>Крепёж</strong> — шляпки не выступают над поверхностью панели; нет следов коррозии (использован нержавеющий крепёж A2).
                    </li>
                    <li>
                        <strong>Узлы</strong> — оконные откосы, углы, цокольный отлив, карнизная планка установлены и загерметизированы.
                    </li>
                    <li>
                        <strong>Документация</strong> — акт скрытых работ по подсистеме, протоколы пробного отрыва анкеров, сертификаты на панели, акт выполненных работ КС-2.
                    </li>
                </ul>

                <div class="install-step-tip">
                    <strong>Гарантия и эксплуатация:</strong> Рекомендуемый плановый осмотр фасада — один раз в год (состояние швов, дренаж). Перегерметизация швов — через 10–12 лет. Срок службы панелей BLP Board — в соответствии с ТУ ООО «Билдингпорт».
                </div>

